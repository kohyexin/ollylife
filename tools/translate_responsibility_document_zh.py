def collect_paragraphs(doc):
    paragraphs = list(doc.paragraphs)
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                paragraphs.extend(cell.paragraphs)
    for section in doc.sections:
        for part in (section.header, section.even_page_header, section.footer, section.even_page_footer):
            paragraphs.extend(part.paragraphs)
    return paragraphs


def copy_rpr(run):
    return deepcopy(run._r.rPr) if run._r.rPr is not None else None


def apply_translation(paragraph, translated):
    nonempty = [run for run in paragraph.runs if run.text]
    if not nonempty:
        return
    if len(nonempty) == 1:
        nonempty[0].text = translated
        return

    # Preserve the two-run label/body styling used by callouts.
    if "  " in translated and len(nonempty) >= 2:
        label, body = translated.split("  ", 1)
        nonempty[0].text = label + "  "
        nonempty[1].text = body
        for run in nonempty[2:]:
            run.text = ""
        return

    # Preserve the footer's tab-separated ownership/classification layout.
    if "\t" in translated:
        left, right = translated.split("\t", 1)
        nonempty[0].text = left
        if len(nonempty) > 1:
            nonempty[1].text = right
            for run in nonempty[2:]:
                run.text = ""
        return

    nonempty[0].text = translated
    for run in nonempty[1:]:
        run.text = ""


def set_chinese_font(doc):
    east_asia = "Microsoft YaHei"
    for style in doc.styles:
        if style.type == 1 and style.element.rPr is not None:
            rfonts = style.element.rPr.get_or_add_rFonts()
            rfonts.set(qn("w:eastAsia"), east_asia)
    for paragraph in collect_paragraphs(doc):
        for run in paragraph.runs:
            rpr = run._element.get_or_add_rPr()
            rfonts = rpr.rFonts
            if rfonts is None:
                from docx.oxml import OxmlElement
                rfonts = OxmlElement("w:rFonts")
                rpr.insert(0, rfonts)
            rfonts.set(qn("w:eastAsia"), east_asia)


